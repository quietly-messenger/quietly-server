// Package storage defines the server's persistence model and the Store
// interface the HTTP layer depends on. The concrete implementation lives in
// storage/postgres; tests may substitute an in-memory store.
package storage

import (
	"context"
	"errors"
	"time"
)

// Sentinel errors. Handlers map these to API error codes.
var (
	ErrNotFound      = errors.New("not found")
	ErrConflict      = errors.New("conflict")
	ErrForbidden     = errors.New("forbidden")
	ErrLimitExceeded = errors.New("limit exceeded")
)

// User is an account (PROTOCOL.md §2).
type User struct {
	ID        string // UUIDv4, assigned by the server
	Username  string
	CreatedAt time.Time
}

// Device is a device record (§2, §7).
type Device struct {
	ID              int
	UserID          string
	IdentityKeyDH   []byte // X25519 public
	IdentityKeySig  []byte // Ed25519 public
	IdentityBinding []byte // signature over identity_key_dh
	SignedPreKeyID  uint32
	SignedPreKey    []byte
	SignedPreKeySig []byte
	// SignedPreKeyRotatedAt is when the current signed prekey was installed.
	// The server nudges the device when it is older than spk_rotation_days
	// (§7.2.1 mitigation 4, audit F-02).
	SignedPreKeyRotatedAt time.Time
	DeliveryToken         []byte // raw token, returned to senders; hash also stored
	DeliveryTokenHash     []byte // SHA-256(token), compared in constant time
	CreatedAt             time.Time
	RevokedAt             *time.Time
	PushEndpoint          *string
}

// OneTimePreKey is an uploaded one-time prekey (§7).
type OneTimePreKey struct {
	ID        uint32
	PublicKey []byte
}

// Message is a store-and-forward envelope (§11). The server holds only
// ciphertext and routing information; there is no sender field.
type Message struct {
	ID                string // ULID, server-assigned
	RecipientUserID   string
	RecipientDeviceID int
	Sealed            []byte
	ServerTS          time.Time
	NotBefore         time.Time // release time for fetch/notify (§15 delivery_jitter_ms)
	TTLExpiresAt      time.Time
}

// Store is the persistence boundary. Implementations must be safe for
// concurrent use. IDs (user UUIDs, message ULIDs, prekey ids) are generated by
// the storage layer where noted.
type Store interface {
	// Users
	CreateUser(ctx context.Context, username string) (*User, error)
	CreateAccountWithDevice(ctx context.Context, username string, d *Device, prekeys []OneTimePreKey) (*User, *Device, error)
	GetUserByUsername(ctx context.Context, username string) (*User, error)
	GetUser(ctx context.Context, userID string) (*User, error)

	// Devices
	CreateDevice(ctx context.Context, d *Device, prekeys []OneTimePreKey) (*Device, error)
	GetDevice(ctx context.Context, userID string, deviceID int) (*Device, error)
	ListDevices(ctx context.Context, userID string) ([]Device, error)
	CountActiveDevices(ctx context.Context, userID string) (int, error)
	RevokeDevice(ctx context.Context, userID string, deviceID int) error
	UpdateSignedPreKey(ctx context.Context, userID string, deviceID int, spkID uint32, spk, sig []byte) error
	UpdateDeliveryToken(ctx context.Context, userID string, deviceID int, token, tokenHash []byte) error
	UpdatePushEndpoint(ctx context.Context, userID string, deviceID int, endpoint *string) error

	// One-time prekeys
	AddOneTimePreKeys(ctx context.Context, userID string, deviceID int, prekeys []OneTimePreKey) error
	TakeOneTimePreKey(ctx context.Context, userID string, deviceID int) (*OneTimePreKey, error)
	CountAvailablePreKeys(ctx context.Context, userID string, deviceID int) (int, error)
	// Prekey issuance idempotency is keyed per (target, window): every fetch
	// for the same target in the same window returns the same OTPK, and the
	// requester is never recorded (TASK-001 C, §7.2.1).
	GetPreKeyIssuance(ctx context.Context, targetUserID string, targetDeviceID int, windowStart time.Time) (*OneTimePreKey, time.Time, error)
	RecordPreKeyIssuance(ctx context.Context, targetUserID string, targetDeviceID int, windowStart time.Time, prekey OneTimePreKey) error
	// IssueOneTimePreKey atomically returns the OTPK already issued for the
	// (target, window) bucket, or takes and records a fresh one — all within a
	// single transaction/lock so concurrent fetches share one OTPK per window
	// (audit F-27). It returns a nil prekey (no error) when the pool is
	// exhausted and no issuance exists for the window.
	IssueOneTimePreKey(ctx context.Context, targetUserID string, targetDeviceID int, windowStart time.Time) (*OneTimePreKey, error)
	// PrunePreKeyIssuances deletes issuance records older than before and
	// reports how many were removed, so the §7.2.1 idempotency table cannot
	// grow without bound (audit F-02 residual).
	PrunePreKeyIssuances(ctx context.Context, before time.Time) (int, error)

	// Messages
	EnqueueMessage(ctx context.Context, m *Message) error
	ListMessages(ctx context.Context, userID string, deviceID int, now time.Time, limit int) ([]Message, error)
	AckMessage(ctx context.Context, userID string, deviceID int, id string) error
	DeleteMessagesForDevice(ctx context.Context, userID string, deviceID int) error
	DeleteExpiredMessages(ctx context.Context, now time.Time) (int, error)
	// PendingMessages returns up to limit messages whose release time is still
	// in the future (not_before > now), ordered by (not_before, id) and
	// strictly after the cursor (afterNotBefore, afterID) — pass the zero
	// cursor for the first page. The keyset cursor keeps post-restart
	// recovery linear in the backlog size (audit F-28).
	PendingMessages(ctx context.Context, now time.Time, afterNotBefore time.Time, afterID string, limit int) ([]Message, error)
}
